def main() -> int:
    ids = [a.upper() for a in sys.argv[1:] if a.upper().startswith("UAT-")]
    targets = ids or list(SPECS)
    for cid in targets:
        s = SPECS.get(cid)
        if not s:
            print("no spec:", cid)
            continue
        size = build(s["src"], OUT / f"{cid}.png", s.get("crop"), s["legend"], s.get("saved_marks"))
        print(f"{cid}: {size}")
    return 0


